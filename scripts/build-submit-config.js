#!/usr/bin/env node
// Writes what the upload function needs from the league data (league slugs and
// member ids, event windows, route segment points and lengths) into the function's
// directory, so it's bundled with it. Run by the Netlify build command after the
// data repo is cloned. No names, Strava names or results go in.
const fs = require('node:fs');
const path = require('node:path');
const { load, loadEvents } = require('../lib/load-data');
const { usingSample } = require('../lib/data-dir');
const { buildSubmitConfig } = require('../lib/submit/process');

const OUT = path.join(__dirname, '..', 'netlify', 'functions', 'submit', 'submit-config.generated.mjs');

const config = buildSubmitConfig({ leagues: load('leagues.yml'), events: loadEvents(), routes: load('routes.yml') });
fs.writeFileSync(OUT, `// Generated by scripts/build-submit-config.js. Don't edit or commit.\nexport default ${JSON.stringify(config, null, '\t')};\n`);

for (const [id, route] of Object.entries(config.routes)) {
	const missing = Object.entries(route.segments).filter(([, s]) => !s.start || !s.end || !(s.length_m > 0)).map(([k]) => k);
	if (missing.length) {
		console.warn(`[submit-config] ${id}: no start/end/length_m on ${missing.join(', ')}, so FIT uploads can't time ${missing.length > 1 ? 'them' : 'it'}`);
	}
}
console.log(`[submit-config] ${config.leagues.length} league(s), ${config.events.length} event(s)${usingSample ? ' (sample data)' : ''}`);
